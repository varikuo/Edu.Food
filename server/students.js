// ── Логин и пароль ─────────────────────────────────────────────────────────
// Логин: транслит фамилии + первая буква имени (Степанова Яна → stepanova.ya).
// Пароль: 6 символов, детерминированы от ФИО — при повторном npm run seed
// выданные ранее пароли не меняются, их можно раздавать спокойно.

const TRANSLIT = {
  а: 'a', б: 'b', в: 'v', г: 'g', д: 'd', е: 'e', ё: 'e', ж: 'zh', з: 'z',
  и: 'i', й: 'y', к: 'k', л: 'l', м: 'm', н: 'n', о: 'o', п: 'p', р: 'r',
  с: 's', т: 't', у: 'u', ф: 'f', х: 'h', ц: 'ts', ч: 'ch', ш: 'sh',
  щ: 'sch', ъ: '', ы: 'y', ь: '', э: 'e', ю: 'yu', я: 'ya'
}

function translit(word) {
  return word
    .toLowerCase()
    .split('')
    .map((ch) => TRANSLIT[ch] ?? '')
    .join('')
}

// Хэш Фньюмана — маленький, стабильный между запусками и платформами
function fnv(str) {
  let h = 2166136261
  for (const ch of str) {
    h ^= ch.codePointAt(0)
    h = Math.imul(h, 16777619)
  }
  return h >>> 0
}

// Без букв, которые путают при диктовке по телефону (o/0, l/1 и т.п.)
const ALPHABET = 'abcdefghjkmnpqrstuvwxyz23456789'

export function makePassword(fio) {
  let h = fnv(fio)
  let out = ''
  for (let i = 0; i < 6; i++) {
    h = Math.imul(h ^ (h >>> 13), 0x5bd1e995)
    h ^= h >>> 16
    out += ALPHABET[Math.abs(h) % ALPHABET.length]
  }
  return out
}

// Возвращает [{ login, password, fio, class }] в порядке табеля.
// Одинаковые фамилии получают нумерацию: vasiliev.d, vasiliev.d2, vasiliev.d3…
export function buildAccounts() {
  const seen = new Map()
  return STUDENTS.map(([fio, klass]) => {
    const [surname, name] = fio.split(' ')
    const base = `${translit(surname)}.${(translit(name ?? '')[0] ?? 'x')}`
    const n = (seen.get(base) ?? 0) + 1
    seen.set(base, n)
    return {
      login: n === 1 ? base : `${base}${n}`,
      password: makePassword(fio),
      fio,
      class: klass
    }
  })
}
